"""Read-only repository/environment inventory; writes audit artifacts only."""
import ast
import hashlib
import importlib.metadata as metadata
import json
import os
import platform
from pathlib import Path
import subprocess
import sys
from datetime import datetime, timezone

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'validation_reports' / 'evidence'
OUT.mkdir(parents=True, exist_ok=True)


def git(*args):
    return subprocess.check_output(['git', *args], cwd=ROOT, text=True).strip()


files, modules, tests = [], [], []
for value in git('ls-files').splitlines():
    path = ROOT / value
    if not path.is_file():
        continue
    data = path.read_bytes()
    files.append(dict(path=value, bytes=len(data), sha256=hashlib.sha256(data).hexdigest()))
    if path.suffix == '.py':
        source = data.decode()
        tree = ast.parse(source)
        definitions = [dict(name=n.name, line=n.lineno, end_line=n.end_lineno,
                            kind=type(n).__name__, doc=ast.get_docstring(n))
                       for n in ast.walk(tree) if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef))]
        imports = [ast.unparse(n) for n in ast.walk(tree) if isinstance(n, (ast.Import, ast.ImportFrom))]
        modules.append(dict(path=value, lines=len(source.splitlines()), definitions=definitions, imports=imports))
        if value.startswith('tests/'):
            tests.extend(dict(path=value, **n) for n in definitions if n['name'].startswith('test_'))

packages = {}
for name in ('napari', 'napari-label-assistant', 'numpy', 'scipy', 'scikit-image', 'zarr',
             'torch', 'qtpy', 'PyQt5', 'PyQt6', 'PySide6', 'superqt', 'pytest', 'pytest-qt',
             'segmentation-models-pytorch', 'timm', 'psutil'):
    try:
        packages[name] = metadata.version(name)
    except metadata.PackageNotFoundError:
        packages[name] = 'not installed in interpreter distribution search path'
import qtpy
import torch
env = dict(timestamp_utc=datetime.now(timezone.utc).isoformat(), commit=git('rev-parse', 'HEAD'),
           remote=git('remote', 'get-url', 'origin'), tracked_status=git('status', '--short', '--untracked-files=no'),
           executable=sys.executable, python=sys.version, platform=platform.platform(),
           machine=platform.machine(), logical_cpus=os.cpu_count(), packages=packages,
           qt_api=qtpy.API_NAME, qt_version=qtpy.QT_VERSION,
           cuda_available=torch.cuda.is_available(), torch_cuda_version=torch.version.cuda,
           cuda_devices=[torch.cuda.get_device_name(i) for i in range(torch.cuda.device_count())],
           env={name: os.environ.get(name) for name in ('QT_QPA_PLATFORM', 'PYTHONPATH', 'XDG_CONFIG_HOME',
                'XDG_CACHE_HOME', 'MPLCONFIGDIR', 'OMP_NUM_THREADS', 'MKL_NUM_THREADS')})
env['meminfo'] = Path('/proc/meminfo').read_text().splitlines()[:5]
inventory = dict(commit=env['commit'], files=files, modules=modules, test_functions=tests,
                 tracked_files=len(files), source_python_files=sum(m['path'].startswith('src/') for m in modules),
                 test_function_count=len(tests), total_python_lines=sum(m['lines'] for m in modules))
(OUT / 'repository_inventory.json').write_text(json.dumps(inventory, indent=2))
(OUT / 'environment.json').write_text(json.dumps(env, indent=2))
index = ['# Source and test index', '', f"Reviewed commit: `{env['commit']}`", '',
         'Generated by `repro/collect_inventory.py`; an inventory is not proof of correctness.', '']
for module in modules:
    index.extend([f"## {module['path']} ({module['lines']} lines)", ''])
    for item in module['definitions']:
        index.append(f"- L{item['line']}–{item['end_line']}: `{item['name']}` ({item['kind']})")
    index.append('')
(OUT / 'source_index.md').write_text('\n'.join(index))
print(json.dumps(dict(commit=env['commit'], tracked_files=len(files), python_lines=inventory['total_python_lines'],
                      test_functions=len(tests), qt=env['qt_api'], cuda=env['cuda_available']), indent=2))
